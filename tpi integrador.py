import numpy as np, sympy as sp, matplotlib.pyplot as plt
t = sp.symbols('t', real=True); n = sp.symbols('n', positive=True, integer=True)
izq, der = sp.pi + t, sp.pi - t                      # tramos (-pi,0) y (0,pi)

def coef(g): return (1/sp.pi)*(sp.integrate(izq*g, (t, -sp.pi, 0)) + sp.integrate(der*g, (t, 0, sp.pi)))
a0, an, bn = [sp.simplify(coef(g)) for g in (1, sp.cos(n*t), sp.sin(n*t))]
print('a0 =', a0, '| an =', an, '| bn =', bn)

def f(v):                                            # f(t) con periodo 2*pi
    v = (np.asarray(v) + np.pi) % (2*np.pi) - np.pi
    return np.where(v < 0, np.pi + v, np.pi - v)
def S(v, N):                                         # suma parcial hasta n = N (bn = 0)
    return float(a0)/2 + sum(float(an.subs(n, k))*np.cos(k*v) for k in range(1, N + 1))

tv = np.linspace(-3*np.pi, 3*np.pi, 2000)
for N in (1, 3, 5): plt.plot(tv, S(tv, N), label=f'hasta n = {N}')
plt.plot(tv, f(tv), 'k', lw=2, label='f(t)')
plt.xlabel('t'); plt.ylabel('f(t)'); plt.legend(); plt.show()
te = np.linspace(-np.pi, np.pi, 2001)
print('Error maximo (n = 5):', np.max(np.abs(f(te) - S(te, 5))))